package com.sekwah.narutoaddon.client.renderer;

import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import com.sekwah.narutoaddon.capabilities.INinjaData;
import com.sekwah.narutoaddon.capabilities.NinjaCapabilityHandler;
import net.minecraft.client.model.PlayerModel;
import net.minecraft.client.player.AbstractClientPlayer;
import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.client.renderer.entity.RenderLayerParent;
import net.minecraft.client.renderer.entity.layers.RenderLayer;
import net.minecraft.client.renderer.texture.OverlayTexture;
import net.minecraft.resources.ResourceLocation;

/**
 * The one shell every body aura is drawn with: the caster's own body, wrapped in light.
 *
 * <p>The shell has to cover the whole body, the way a chakra mode does in the source material, so it
 * is built in three passes over the same body parts:</p>
 * <ol>
 *   <li>a solid glowing base over the skin, which is what actually colours the whole body;</li>
 *   <li>the moving plasma - a tiled noise texture drawn additively and scrolled by the game clock,
 *       which is what makes it look alive;</li>
 *   <li>a dimmer halo just outside the body, which softens the edge.</li>
 * </ol>
 *
 * <p>Only the body parts are drawn - head, torso, arms and legs - never the skin's clothing overlays
 * (jacket, sleeves, pants). Those overlays sit outside the body by design, so a shell that copied
 * them poked out through armour and clothes.</p>
 *
 * <p>Which aura to draw, and its colour, come from {@link ModeAura}; this class only knows how to put
 * a body-shaped glow on screen.</p>
 */
public class ModeAuraLayer extends RenderLayer<AbstractClientPlayer, PlayerModel<AbstractClientPlayer>> {

    /** Flat white 16x16 sheet, tinted by the vertex colour; the base that covers the whole body. */
    private static final ResourceLocation SHEET =
            new ResourceLocation("narutomod", "textures/entity/chakra_cloak.png");

    /** Tiling plasma noise for the moving pass; generated by {@code tmp/make_mode_aura.py}. */
    private static final ResourceLocation NOISE =
            new ResourceLocation("narutoaddon", "textures/entity/mode_aura.png");

    /** Full-bright light, so a glowing aura does not go dark in a cave or at night. */
    private static final int GLOW_LIGHT = 0xF000F0;

    /** How much wider the halo pass is than the core. Small: the shell must stay on the body. */
    private static final float HALO = 1.05f;

    public ModeAuraLayer(RenderLayerParent<AbstractClientPlayer, PlayerModel<AbstractClientPlayer>> renderer) {
        super(renderer);
    }

    @Override
    public void render(PoseStack poseStack, MultiBufferSource buffer, int packedLight,
                       AbstractClientPlayer player,
                       float limbSwing, float limbSwingAmount, float partialTick,
                       float ageInTicks, float netHeadYaw, float headPitch) {
        INinjaData ninjaData = player.getCapability(NinjaCapabilityHandler.NINJA_DATA).orElse(null);
        ModeAura aura = ModeAura.resolve(ninjaData);
        if (aura == null) {
            return;
        }
        PlayerModel<AbstractClientPlayer> model = this.getParentModel();
        float alpha = aura.alphaAt(ageInTicks);

        // Pass 1: the body itself. A flat sheet tinted by the aura's colour and drawn emissive, so
        // the whole skin lights up instead of showing a faint film over a few highlights.
        RenderType baseType = aura.emissive()
                ? RenderType.entityTranslucentEmissive(SHEET)
                : RenderType.entityTranslucent(SHEET);
        draw(model, poseStack, buffer.getBuffer(baseType), aura, alpha, aura.scale());

        // Pass 2: flowing plasma over the body, additively blended so it adds light rather than
        // hiding the skin. Kept thin on purpose: the moving pass is the loudest part of the effect,
        // and at full strength it drowned the body it is supposed to decorate.
        VertexConsumer flow = buffer.getBuffer(RenderType.energySwirl(NOISE,
                0.0f, (ageInTicks * 0.008f) % 1.0f));
        draw(model, poseStack, flow, aura, alpha * 0.5f, aura.scale());

        // Pass 3: the soft edge - the same plasma, wider and much dimmer.
        VertexConsumer halo = buffer.getBuffer(RenderType.energySwirl(NOISE,
                0.5f, (ageInTicks * -0.006f) % 1.0f));
        draw(model, poseStack, halo, aura, alpha * 0.25f, aura.scale() * HALO);
    }

    /**
     * Draws the body-shaped shell.
     *
     * <p>The whole model is rendered, overlay layers included. Copying only the bare limbs was the
     * second version's mistake: the skin's own hair, jacket, sleeves and pants sit a hair outside the
     * body, so the shell covered the skin but left those layers poking out of it. Drawing the full
     * model with a slightly larger scale covers everything the player actually shows.</p>
     */
    private static void draw(PlayerModel<AbstractClientPlayer> model, PoseStack poseStack,
                             VertexConsumer consumer, ModeAura aura, float alpha, float scale) {
        poseStack.pushPose();
        poseStack.scale(scale, scale, scale);
        model.renderToBuffer(poseStack, consumer, GLOW_LIGHT, OverlayTexture.NO_OVERLAY,
                aura.red(), aura.green(), aura.blue(), alpha);
        poseStack.popPose();
    }
}
