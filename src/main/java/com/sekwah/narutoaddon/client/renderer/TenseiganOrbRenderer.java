package com.sekwah.narutoaddon.client.renderer;

import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import com.sekwah.narutoaddon.abilities.jutsus.TenseiganAbility;
import com.sekwah.narutoaddon.capabilities.INinjaData;
import com.sekwah.narutoaddon.capabilities.NinjaCapabilityHandler;
import com.sekwah.narutoaddon.client.model.jutsu.TruthSeekerOrbModel;
import com.sekwah.narutoaddon.skills.SkillTree;
import net.minecraft.client.Camera;
import net.minecraft.client.Minecraft;
import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.phys.Vec3;
import net.minecraftforge.api.distmarker.Dist;
import net.minecraftforge.client.event.RenderLevelStageEvent;
import net.minecraftforge.eventbus.api.SubscribeEvent;
import net.minecraftforge.fml.common.Mod;

/**
 * Draws the Truth-Seeking Orbs of the Tenseigan branch: the same halo the Six Paths mode wears,
 * painted in the eye's own turquoise instead of black.
 *
 * <p>The geometry and the layout are deliberately the ones of {@link SixPathsOrbRenderer} - a ring
 * behind the caster's back, turning slowly, bobbing with the game clock - so a caster who has seen
 * the Six Paths halo reads this one instantly. The only differences are the colour and the fact that
 * the surface is emissive: the orbs are lit by themselves, not by the world, which is what makes them
 * read as glowing chakra rather than as painted stone.</p>
 *
 * <p>Shown only while the eye is open and the {@code mechanic:truth_orbs} node is bought; the very
 * same conditions {@code TruthOrbEvents} uses for the damage reduction, so the picture and the
 * mechanic can never disagree.</p>
 */
@Mod.EventBusSubscriber(value = Dist.CLIENT, modid = "narutoaddon", bus = Mod.EventBusSubscriber.Bus.FORGE)
public final class TenseiganOrbRenderer {

    /** Soft radial glow drawn on the sphere; generated by {@code tmp/make_tenseigan_orb.py}. */
    private static final ResourceLocation ORB_TEXTURE =
            new ResourceLocation("narutoaddon", "textures/entity/tenseigan_orb.png");

    /** The eye's colour: a pale turquoise, bright enough to read as light. */
    private static final float RED = 0.36f;
    private static final float GREEN = 1.0f;
    private static final float BLUE = 0.92f;

    /** How many orbs the halo carries, matching the Six Paths halo. */
    private static final int ORB_COUNT = 6;

    private TenseiganOrbRenderer() {
    }

    @SubscribeEvent
    public static void onRenderLevel(RenderLevelStageEvent event) {
        if (event.getStage() != RenderLevelStageEvent.Stage.AFTER_ENTITIES) {
            return;
        }
        Minecraft mc = Minecraft.getInstance();
        if (mc.level == null || mc.player == null) {
            return;
        }
        Camera camera = mc.gameRenderer.getMainCamera();
        if (!camera.isInitialized()) {
            return;
        }
        PoseStack poseStack = event.getPoseStack();
        MultiBufferSource.BufferSource buffer = mc.renderBuffers().bufferSource();
        float partialTick = event.getPartialTick();
        long gameTime = mc.level.getGameTime();
        boolean drawn = false;

        for (Player player : mc.level.players()) {
            INinjaData ninjaData = player.getCapability(NinjaCapabilityHandler.NINJA_DATA).orElse(null);
            if (ninjaData == null || !TenseiganAbility.isActive(ninjaData)) {
                continue;
            }
            if (!SkillTree.hasUnlock(ninjaData.getSkillData().getUnlocked(), "mechanic:truth_orbs")) {
                continue;
            }
            // The ring shrinks as the orbs are thrown: it is a resource, not decoration.
            int orbs = TenseiganAbility.orbs(ninjaData);
            if (orbs <= 0) {
                continue;
            }
            renderOrbs(player, orbs, camera, poseStack, buffer, partialTick, gameTime);
            drawn = true;
        }
        if (drawn) {
            buffer.endBatch();
        }
    }

    private static void renderOrbs(Player player, int count, Camera camera, PoseStack poseStack,
                                   MultiBufferSource.BufferSource buffer, float partialTick, long gameTime) {
        double x = player.xo + (player.getX() - player.xo) * partialTick;
        double y = player.yo + (player.getY() - player.yo) * partialTick;
        double z = player.zo + (player.getZ() - player.zo) * partialTick;
        float yaw = player.yRotO + (player.getYRot() - player.yRotO) * partialTick;

        double yawRad = Math.toRadians(yaw);
        double forwardX = -Math.sin(yawRad);
        double forwardZ = Math.cos(yawRad);
        double rightX = Math.cos(yawRad);
        double rightZ = Math.sin(yawRad);

        double height = player.getBbHeight() * 0.72d;
        double behind = 0.75d;
        double ringRadius = 0.9d;

        Vec3 camPos = camera.getPosition();

        double centerX = x - forwardX * behind;
        double centerY = y + height;
        double centerZ = z - forwardZ * behind;

        // Emissive translucent: the orbs light themselves and never darken with the time of day.
        VertexConsumer consumer = buffer.getBuffer(RenderType.entityTranslucentEmissive(ORB_TEXTURE));

        poseStack.pushPose();
        poseStack.translate(-camPos.x, -camPos.y, -camPos.z);

        // A slow breath, so the halo reads as living chakra rather than as a static prop.
        float pulse = 1.0f + 0.08f * (float) Math.sin((gameTime + partialTick) * 0.12d);
        double coreRadius = 0.12d * pulse;
        double shellRadius = 0.21d * pulse;
        double bob = Math.sin(gameTime * 0.05d) * 0.04d;

        for (int i = 0; i < count; i++) {
            double angle = (Math.PI * 2.0d * i / count) + (gameTime + partialTick) * 0.03d;
            double cos = Math.cos(angle) * ringRadius;
            double sin = Math.sin(angle) * ringRadius;
            double px = centerX + rightX * cos;
            double py = centerY + sin + bob;
            double pz = centerZ + rightZ * cos;

            // Outer glow first, then the bright core inside it.
            TruthSeekerOrbModel.renderSphere(poseStack, consumer, px, py, pz, shellRadius,
                    0xF000F0, RED, GREEN, BLUE, 0.35f);
            TruthSeekerOrbModel.renderSphere(poseStack, consumer, px, py, pz, coreRadius,
                    0xF000F0, RED, GREEN, BLUE, 1.0f);
        }

        poseStack.popPose();
    }
}
