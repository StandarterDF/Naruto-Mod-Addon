package com.sekwah.narutoaddon.client.renderer.entity.jutsuprojectile;

import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import com.sekwah.narutoaddon.client.model.jutsu.TruthSeekerOrbModel;
import com.sekwah.narutoaddon.entity.jutsuprojectile.ChakraOrbEntity;
import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.client.renderer.entity.EntityRenderer;
import net.minecraft.client.renderer.entity.EntityRendererProvider;
import net.minecraft.resources.ResourceLocation;

/**
 * Draws a chakra sphere in flight with the shared Truth-Seeking Orb geometry: black and solid for
 * the Six Paths orb, turquoise and self-lit for the Tenseigan one.
 */
public class ChakraOrbRenderer extends EntityRenderer<ChakraOrbEntity> {

    private static final ResourceLocation BLACK =
            new ResourceLocation("minecraft", "textures/block/black_concrete.png");

    /** Soft radial glow generated by {@code tmp/make_tenseigan_orb.py}. */
    private static final ResourceLocation GLOW =
            new ResourceLocation("narutoaddon", "textures/entity/tenseigan_orb.png");

    /** Colour of the Tenseigan sphere: the same turquoise as its halo. */
    private static final float RED = 0.36f;
    private static final float GREEN = 1.0f;
    private static final float BLUE = 0.92f;

    public ChakraOrbRenderer(EntityRendererProvider.Context context) {
        super(context);
    }

    @Override
    public void render(ChakraOrbEntity entity, float entityYaw, float partialTicks, PoseStack poseStack,
                       MultiBufferSource buffer, int packedLight) {
        poseStack.pushPose();
        float radius = entity.getRenderRadius();
        if (entity.getStyle() == 0) {
            VertexConsumer consumer = buffer.getBuffer(RenderType.entitySolid(BLACK));
            TruthSeekerOrbModel.renderSphere(poseStack, consumer, 0.0d, 0.0d, 0.0d, radius, 0xF000F0);
        } else {
            VertexConsumer consumer = buffer.getBuffer(RenderType.entityTranslucentEmissive(GLOW));
            // A dim outer shell around a bright core, so the sphere reads as a light source.
            TruthSeekerOrbModel.renderSphere(poseStack, consumer, 0.0d, 0.0d, 0.0d,
                    radius * 1.35d, 0xF000F0, RED, GREEN, BLUE, 0.35f);
            TruthSeekerOrbModel.renderSphere(poseStack, consumer, 0.0d, 0.0d, 0.0d,
                    radius, 0xF000F0, RED, GREEN, BLUE, 1.0f);
        }
        poseStack.popPose();
        super.render(entity, entityYaw, partialTicks, poseStack, buffer, packedLight);
    }

    @Override
    public ResourceLocation getTextureLocation(ChakraOrbEntity entity) {
        return BLACK;
    }
}
